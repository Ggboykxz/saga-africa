type Lang = "fr" | "en";
const DICTS: Record<Lang, Dict> = { fr, en };

const I18nCtx = createContext<{ lang: Lang; t: (k: string) => string; setLang: (l: Lang) => void }>({
  lang: "fr",
  t: (k) => k,
  setLang: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    const saved = (typeof localStorage !== "undefined" && localStorage.getItem("saga_lang")) as Lang | null;
    if (saved === "fr" || saved === "en") setLangState(saved);
    else if (typeof navigator !== "undefined" && navigator.language?.startsWith("en")) setLangState("en");
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    try { localStorage.setItem("saga_lang", l); } catch {}
  };

  const t = (k: string) => DICTS[lang][k] ?? DICTS.en[k] ?? k;

  const value = useMemo(() => ({ lang, t, setLang }), [lang]);
  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  return useContext(I18nCtx);
}
